package.path = "test/?.lua;test/mock/?.lua;" .. package.path
local h, UI, window, section, check, done = require("ui_library_support").new("values")
local snapshots = {}
local a = section:Toggle({ Id = "a", Default = false, Callback = function()
	snapshots[#snapshots + 1] = window:GetValues()
end })
local b = section:Slider({ Id = "b", Min = 1, Max = 10, Default = 2 })
local choice = section:Dropdown({ Id = "choice", Multi = true, Options = { "a", "b" }, Default = { "a" } })
local empty = section:Dropdown({ Id = "empty", Options = { false, true }, Default = false })
local transient = section:Input({ Id = "transient", Default = "private", Persist = false })
local color = section:ColorPicker({ Id = "color", Alpha = 0.25 })
local values = window:GetValues()
check("form snapshots retain false, selections and color alpha", values.a == false and values.empty == false and values.choice[1] == "a" and values.color.Alpha == 0.25)
values.choice[1] = "b"
check("snapshots are detached from control state", choice:Get()[1] == "a")
local selected = window:GetValues({ Ids = { "a", "transient" }, PersistOnly = true })
check("selection and persistence filters compose", selected.a == false and selected.transient == nil and selected.b == nil)
local ok = window:SetValues({ a = true, b = "bad" }, { Silent = false })
check("invalid batch values never partially apply", not ok and not a:Get() and b:Get() == 2 and #snapshots == 0)
check("callbacks observe the completed batch", window:SetValues({ a = true, b = 7 }, { Silent = false }) and #snapshots == 1 and snapshots[1].b == 7)
check("batch updates are silent by default", window:SetValues({ a = false }) and #snapshots == 1)
check("explicit Clear supports nil without losing false", window:SetValues({}, { Clear = { "empty" } }) and empty:Get() == nil)
check("a duplicate write and Clear fails without changing state", not window:SetValues({ a = true }, { Clear = { "a" } }) and not a:Get())
check("malformed options return a clear failure", not window:SetValues({ a = true }, { Silent = 0 }) and not window:ResetValues({ Ids = { missing = "a" } }))
check("sparse Id lists cannot silently skip requested values", not window:ResetValues({ Ids = { [2] = "a" } }) and not window:SetValues({}, { Clear = { [2] = "empty" } }))
choice:Set({ "b" }); transient:Set("changed")
check("selected defaults reset without touching other values", window:ResetValues({ Ids = { "choice", "a" } }) and choice:IsDefault() and transient:Get() == "changed")
local default = choice:GetDefault(); default[1] = "b"
check("default inspection is detached", choice:GetDefault()[1] == "a")
local records = window:InspectValues({ Ids = { "b", "a" } })
check("inspection is deterministic and describes changed values", #records == 2 and records[1].Id == "a" and records[2].Id == "b" and records[2].Changed and records[2].Valid)
local options = choice:GetOptions(); options[1].Label = "mutated"
check("option inspection is detached", choice:GetOptions()[1].Label == "a")
choice:Clear(true)
check("multi-select Clear restores an empty selection", #choice:Get() == 0)
local malformed = {}; malformed[1] = malformed
check("cyclic caller data is rejected without corrupting state", not window:SetValues({ choice = malformed }) and #choice:Get() == 0)
window:Destroy()
check("destroyed windows reject form mutations", not window:SetValues({ a = true }) and not window:CommitInputs())
done()
