-- Settings search uses static metadata and preserves native drafts in both views.
package.path = "test/?.lua;test/mock/?.lua;" .. package.path
local F = require("coding_fixture")
local suite = F.suite("Settings search")
local case, check = suite.case, suite.check

case("catalog ranks exact labels and never loads configuration", function()
	local f = F.new()
	local catalog = f.env.require("runtime/settings_catalog")
	local results = catalog.search("Request timeout")
	check("exact label resolves to the field", results[1].path == "agent.requestTimeout" and results[1].category == "agent")
	check("search has no configuration dependency", f.loaded["runtime/config"] == nil)
	check("terms are AND matched across metadata", catalog.search("delegation depth")[1].path == "agent.subagentDepth")
	check("punctuation is literal", #catalog.search("%.*") == 0)
	check("blank query has no results", #catalog.search("   ") == 0)
	local limited, total = catalog.search("agent", 2)
	check("result window reports the full count", #limited == 2 and total > 2)
	results[1].label = "Changed by caller"
	check("results are independent snapshots", catalog.search("Request timeout")[1].label == "Request timeout")
	f.close()
end)

case("dialog searches hidden categories without recreating a draft", function()
	local f = F.ui(900, 650)
	local config = f.env.require("runtime/config")
	config.set("agent.customInstructions", "Private saved instructions")
	local dialog = assert(f.env.require("ui/panels/settingsdialog").open("agent"))
	f.h.settle(0.4)
	local field = assert(f.h.byName("CustomInstructions")):FindFirstChildWhichIsA("TextBox")
	field.Text = "An unfinished draft"
	dialog.search.setQuery("Private saved instructions")
	check("saved values are not indexed", #dialog.search.matches == 0)
	dialog.search.setQuery("text scale")
	check("another category is searchable", dialog.search.matches[1].path == "ui.fontScale")
	f.h.click(assert(f.h.byName("SettingResult_ui.fontScale")))
	f.h.settle(0.3)
	check("result opens the target category", dialog.activeCategory() == "general" and dialog.search.query == "")
	dialog.select("agent"); f.h.settle(0.2)
	check("draft and native instance survive searching", f.h.byName("CustomInstructions"):FindFirstChildWhichIsA("TextBox") == field
		and field.Text == "An unfinished draft")
	check("search did not save the draft", config.get("agent.customInstructions") == "Private saved instructions")
	check("exact reveal accepts a known category", dialog.reveal("agent", "agent.requestTimeout"))
	check("unknown category is rejected", not dialog.reveal("missing", "ui.fontScale"))
	f.h.settle(0.2); dialog.close(); f.h.settle(0.3); f.healthy(); f.close()
end)

case("stacked settings restore all panes after an empty result", function()
	local f = F.ui(430, 700)
	local panel = f.env.require("ui/panels/settings").new(f.host)
	f.h.settle(0.4)
	panel.search.setQuery("nothing matches this phrase")
	check("empty result gives feedback", f.h.byName("SettingsSearchCount").Text == "No settings found.")
	check("search hides panes without destroying them", f.h.byName("Pane_agent").Visible == false)
	panel.search.setQuery("")
	check("clearing restores panes", f.h.byName("Pane_agent").Visible and f.h.byName("Pane_general").Visible)
	check("path metadata finds a toggle", f.env.require("ui/settings_search").find(f.h.byName("Pane_agent"), "agent.requestUnlimited") ~= nil)
	f.host:Destroy(); f.h.settle(0.2); f.healthy(); f.close()
end)

suite.finish()
