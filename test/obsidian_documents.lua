-- Native note reads reject changing revisions; draft recovery never evicts edits.
package.path = "test/?.lua;test/mock/?.lua;" .. package.path
local F = require("workspace_fixture")
local suite = F.suite("Native Obsidian documents")
local check, case = suite.check, suite.case
local revision = string.rep("a", 64)
case("UTF-8 pages bind to one revision and complete byte count", function()
	local f = F.new(); local docs = f.env.require("runtime/obsidian_document")
	local reader = docs.reader("notes", "Example.md")
	check("first partial page retained", reader.accept({ content = "界", revision = revision, bytes = 4, offset = 1, nextOffset = 4, eof = false }) == false)
	local document = assert(reader.accept({ content = "x", revision = revision, bytes = 4, offset = 4, eof = true }))
	check("complete Unicode note assembled", document.content == "界x" and document.bytes == 4)
	reader = docs.reader("notes", "Example.md")
	reader.accept({ content = "a", revision = revision, bytes = 2, offset = 1, nextOffset = 2, eof = false })
	local result, why = reader.accept({ content = "b", revision = string.rep("b", 64), bytes = 2, offset = 2, eof = true })
	check("changed revision stops read", result == nil and why:find("changed", 1, true) ~= nil)
	check("CRLF line style preserved on save", docs.savedText({ content = "a\r\nb\r\n" }, "new\ntext\n") == "new\r\ntext\r\n")
	f.close()
end)
case("draft capacity never evicts an unsaved note", function()
	local f = F.new(); local drafts = f.env.require("runtime/obsidian_drafts")
	for index = 1, drafts.limit do
		local doc = { vault = "notes", path = index .. ".md", content = "original", revision = revision }
		local entry = assert(drafts.reserve("notes", doc.path, doc)); assert(drafts.update(entry, "draft " .. index))
	end
	local overflow, why = drafts.reserve("notes", "overflow.md", { vault = "notes", path = "overflow.md", content = "" })
	check("new draft refused at capacity", overflow == nil and why ~= nil)
	check("first draft still recoverable", drafts.get("notes", "1.md").text == "draft 1")
	local entry = drafts.get("notes", "1.md")
	check("oversized input refused without replacing text", not drafts.update(entry, string.rep("x", 1048577)) and entry.text == "draft 1")
	drafts.remove("notes", "1.md")
	check("discard releases a recovery slot", drafts.reserve("notes", "overflow.md", { vault = "notes", path = "overflow.md", content = "" }) ~= nil)
	f.close()
end)
case("listing continuation and paths are validated", function()
	local f = F.new(); local listings = f.env.require("runtime/obsidian_listing")
	check("safe list accepted", listings.validate({ data = { { path = "Notes/A.md", bytes = 20 } }, offset = 1, total = 2, nextOffset = 2 }, 1) ~= nil)
	check("wrong next offset refused", listings.validate({ data = { { path = "A.md" } }, offset = 1, total = 2, nextOffset = 3 }, 1) == nil)
	check("hidden paths refused", listings.validate({ data = { { path = ".hidden/A.md" } }, offset = 1, total = 1 }, 1) == nil)
	f.close()
end)
suite.finish()
