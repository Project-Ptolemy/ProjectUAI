-- Real startup milestones, slow-state timing, safe failure and owned splash life.
package.path = "test/?.lua;test/mock/?.lua;" .. package.path
local F = require("coding_fixture")
local suite = F.suite("Boot progress")
local case, check = suite.case, suite.check

case("module count never turns into fictitious completion", function()
	local f = F.new()
	local state = f.env.require("runtime/boot_progress").new(10)
	state.module(98, 100, 11)
	local view = state.snapshot(12)
	check("count stays independent of startup milestones", view.count == 98 and view.index == 1 and view.stages[2].status == "pending")
	check("no progress triggers slow-state guidance", state.snapshot(19).slow)
	state.phase("Reading saved conversations", 20)
	check("real activity clears slow-state guidance", not state.snapshot(21).slow)
	check("stage cannot regress", state.stage("restore", nil, 22) and not state.stage("prepare", nil, 23))
	check("unknown stage is ignored", not state.stage("pretend", nil, 24))
	state.stage("interface", nil, 25); state.finish(nil, 26)
	view = state.snapshot(100)
	check("completion freezes elapsed time", view.status == "ready" and view.elapsed == 16)
	check("all milestones completed with lazy modules remaining", view.count == 98 and view.stages[3].status == "done")
	view.stages[1].label = "Mutated"
	check("snapshot mutations cannot change model", state.snapshot(100).stages[1].label == "Prepare")
	check("terminal completion rejects late failures", not state.fail(101))
	f.close()
end)

case("failure retains its stage without inventing success", function()
	local f = F.new()
	local state = f.env.require("runtime/boot_progress").new(0)
	state.stage("restore", nil, 2); state.fail(4)
	local view = state.snapshot(50)
	check("failed stage remains explicit", view.stages[1].status == "done" and view.stages[2].status == "failed" and view.stages[3].status == "pending")
	check("failure freezes timing and prevents completion", view.elapsed == 4 and not state.finish(nil, 60))
	check("failure provides recovery guidance", view.detail:find("executor console", 1, true) ~= nil)
	f.close()
end)

case("native splash fits narrow screens and releases finishing work", function()
	local f = F.new()
	f.h.sandbox.os = setmetatable({ clock = function() return f.h.sched.now end }, { __index = os })
	f.h.setViewport(320, 568)
	local boot = f.env.require("ui/boot").show()
	f.h.settle(0.1)
	check("startup does not load application styling", f.loaded["ui/theme"] == nil and f.loaded["ui/primitives"] == nil)
	check("card fits narrow width", boot.card.Size.X.Offset <= 296)
	boot.step("private/module/name", 12, 40)
	check("module paths stay out of loading copy", not f.h.textOf(boot.screen):find("private/module/name", 1, true))
	-- settle stops once scheduled work is empty; a live Heartbeat can remain.
	f.h.frame(8.2)
	check("elapsed time and slow guidance follow the live clock", boot.elapsed.Text ~= "0.0 s" and boot.note.Text:find("Still working", 1, true))
	boot.stage("restore"); boot.stage("interface"); boot.done()
	check("ready has complete milestones", f.h.byName("BootStage3", boot.screen):FindFirstChild("StageTrack"):GetAttribute("StageStatus") == "done")
	local screen = boot.screen
	boot.destroy(); f.h.settle(2)
	check("explicit destroy cancels the delayed exit", screen.Parent == nil and boot.screen == nil)
	f.healthy(); f.close()
end)

case("failed splash remains readable until dismissed and can be replaced", function()
	local f = F.new()
	f.h.setViewport(844, 390)
	local boot = f.env.require("ui/boot").show()
	boot.stage("restore"); boot.fail("synthetic-private-credential")
	f.h.settle(10)
	check("failure stays available", boot.screen and boot.close.Visible)
	check("raw exception is not displayed", not f.h.textOf(boot.screen):find("synthetic-private-credential", 1, true))
	check("failed stage has its own state", f.h.byName("BootStage2", boot.screen):FindFirstChild("StageTrack"):GetAttribute("StageStatus") == "failed")
	f.h.click(boot.close)
	check("dismiss removes the failed surface", boot.screen == nil)
	boot.show(); boot.done(); f.h.settle(2)
	check("a replacement finishes normally", boot.screen == nil)
	f.healthy(); f.close()
end)

suite.finish()
