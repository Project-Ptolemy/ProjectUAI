-- Conversation recovery and search use real session ownership and mock files.
package.path = "test/?.lua;test/mock/?.lua;" .. package.path
local F = require("workspace_fixture")
local suite = F.suite("Conversation quality of life")
local check, case = suite.check, suite.case
case("pins, drafts and bounded task plans survive a client restart", function()
	local f = F.new()
	local sessions = f.env.require("agent/session")
	local older = assert(sessions.newThread({ id = "pinned-chat", title = "Pinned work" }))
	local newer = assert(sessions.newThread({ id = "recent-chat", title = "Recent work" }))
	newer.updatedAt = older.updatedAt + 1000
	check("pin action succeeds", older.setPinned(true))
	check("pinned conversation wins list order", sessions.list()[1] == older)
	check("draft accepted", older.setDraft({ text = "Keep this unsent request", attachments = {}, expanded = true }))
	f.env.require("agent/state").setTodos({ { text = "Finish parser", status = "active", note = string.rep("n", 900) }, { text = "Read source", status = "done" } }, older)
	assert(older.persist())
	local raw = assert(f.h.files["UAI/sessions/pinned-chat.json"])
	local saved = f.h.json.decode(raw)
	check("draft is inside the conversation file", saved.draft.text == "Keep this unsent request")
	check("task notes are bounded", #saved.todos.items[1].note <= 600)
	sessions.beginShutdown()
	f.loaded["agent/session"] = nil
	local restored = f.env.require("agent/session")
	check("saved histories restore", restored.restore() >= 1)
	local thread = assert(restored.get("pinned-chat"))
	check("pin and draft restored", thread.metadata.pinned and thread.draft.text == saved.draft.text)
	check("unfinished tasks resume pending", thread.todos[1].status == "pending" and thread.todos[2].status == "done")
	f.healthy(); f.close()
end)
case("unread notices follow visible readers and remain isolated", function()
	local f = F.new(); local sessions = f.env.require("agent/session")
	local a = assert(sessions.newThread({ id = "visible-chat" }))
	local b = assert(sessions.newThread({ id = "background-chat", activate = false }))
	local owner = {}; a.setViewed(owner, true)
	a.emit("assistant:text", { text = "Visible reply" })
	b.emit("assistant:complete", {})
	check("empty completions do not claim new messages", b.metadata.unread == 0)
	b.emit("assistant:text", { text = "Background reply" }); b.emit("error", { message = "Failed request" })
	check("only background reply is unread", a.metadata.unread == 0 and b.metadata.unread == 1 and b.metadata.failures == 1)
	a.setViewed(owner, false); a.emit("assistant:text", { text = "While minimized" })
	check("hidden active conversation is unread", a.metadata.unread == 1)
	b.setViewed(owner, true)
	check("opening a reader clears its badges", b.metadata.unread == 0 and b.metadata.failures == 0 and a.metadata.unread == 1)
	f.healthy(); f.close()
end)
case("transcript search preserves ids, literal phrases, exclusions and continuations", function()
	local f = F.new(); local search = f.env.require("runtime/transcript_search")
	local events = {}
	for index = 1, 60 do events[index] = { transcriptId = index, kind = "assistant:text", text = "Build exact phrase " .. tostring(index) } end
	events[59].text = "Build exact phrase excluded"
	local page = search.page(events, '"exact phrase" -excluded', { limit = 10 })
	check("newest exact match first", page.items[1].id == 60 and #page.items == 10)
	for _, hit in ipairs(page.items) do check("excluded text omitted", hit.id ~= 59) end
	local second = search.page(events, '"exact phrase" -excluded', { before = page.nextBefore, limit = 10 })
	check("next page cannot repeat the boundary", second.items[1].id < page.items[#page.items].id)
	local legacy = { title = "Old conversation", log = {}, ctx = { messages = { { role = "user", content = "Remember a legacy-only request" } } } }
	check("context-only saves remain searchable", f.env.require("runtime/conversation_search").find(legacy, "Universal", "legacy-only") ~= nil)
	check("bounded search reports omitted long text", search.page({ { transcriptId = 1, kind = "user", text = string.rep("x", 20000) } }, "x").clipped)
	f.healthy(); f.close()
end)
case("recovery limits never save a partial new draft", function()
	local f = F.new(); local session = assert(f.env.require("agent/session").newThread({ id = "draft-limit" }))
	assert(session.setDraft({ text = "Complete prior draft" }))
	local ok, why = session.setDraft({ text = string.rep("x", 1024 * 1024 + 1) })
	check("oversized draft rejected with reason", not ok and type(why) == "string")
	check("prior complete recovery remains intact", session.draft.text == "Complete prior draft")
	session.setEphemeral(true); session.setDraft({ text = "Only in memory" }); f.h.sched.advance(2)
	check("ephemeral draft creates no history file", f.h.files["UAI/sessions/draft-limit.json"] == nil)
	f.healthy(); f.close()
end)
suite.finish()
